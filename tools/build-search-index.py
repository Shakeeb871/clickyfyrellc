#!/usr/bin/env python3
"""Build assets/js/search-index.js from the site's HTML pages.

Run after adding or editing pages:  python3 tools/build-search-index.py
"""
import glob
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {"search.html", "404.html"}
# Repeated chrome (menus, popups, footer) would make every page match everything
CHROME = re.compile(
    r"<!--\s*=+\s*(Preloader|Search Popup|Offcanvus|Mobile Menu|Header|Footer)[^>]*Start[^>]*-->.*?"
    r"<!--\s*=+\s*\1[^>]*End[^>]*-->",
    re.S | re.I,
)


def text(fragment):
    fragment = re.sub(r"<(script|style|svg)\b.*?</\1>", " ", fragment, flags=re.S | re.I)
    fragment = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()


pages = []
for path in sorted(glob.glob(os.path.join(ROOT, "*.html"))):
    name = os.path.basename(path)
    if name in SKIP:
        continue
    src = open(path, encoding="utf-8", errors="ignore").read()
    body = src.split("<body", 1)[-1].split(">", 1)[-1]
    body = CHROME.sub(" ", body)
    body = re.sub(r"<(header|footer|nav)\b.*?</\1>", " ", body, flags=re.S | re.I)
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", body, re.S)
    title = text(h1.group(1)) if h1 else ""
    if not title or len(title) > 60:
        title = name[:-5].replace("-", " ").title()
    headings = [text(h) for h in re.findall(r"<h[2-4][^>]*>(.*?)</h[2-4]>", body, re.S)]
    headings = [h for h in dict.fromkeys(headings) if 2 < len(h) < 120][:25]
    pages.append({
        "url": name,
        "title": title.title() if title.isupper() else title,
        "headings": headings,
        "text": text(body)[:4000],
    })

out = os.path.join(ROOT, "assets", "js", "search-index.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build-search-index.py - do not edit by hand\n")
    f.write("window.SEARCH_INDEX = " + json.dumps(pages, ensure_ascii=False) + ";\n")
print(f"Indexed {len(pages)} pages -> {os.path.relpath(out, ROOT)}")
